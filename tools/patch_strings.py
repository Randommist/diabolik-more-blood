def strings(b):
    i=LO
    while i<HI:
        if b[i] and b[i-1]==0:
            e=b.index(b'\0',i)
            try:t=b[i:e].decode('cp932')
            except UnicodeDecodeError:i=e+1;continue
            yield i,e-i,t;i=e+1
        else:i+=1
def window(off):va=off-0xc0;return (va+0x8000)>>16
def refs(b,off):
    va=off-0xc0;lo=va&0xffff;hi=(va>>16)+(1 if lo&0x8000 else 0);out=[]
    code=b[0xc0:0xc0+0x329824]
    for i in range(0,len(code)-4,4):
        w=struct.unpack_from('<I',code,i)[0]
        if (w>>26)==9 and (w&0xffff)==lo:
            rs=(w>>21)&31
            for k in range(1,12):
                if i-4*k<0:break
                q=struct.unpack_from('<I',code,i-4*k)[0]
                if (q>>26)==15 and (q&0xffff)==hi and ((q>>16)&31)==rs:out.append(('code',i+0xc0));break
    for j in range(0,len(b)-3,4):
        if j>=0xc0+0x329824 or True:
            if struct.unpack_from('<I',b,j)[0]==va and not (0xc0<=j<0xc0+0x329824):out.append(('data',j))
    return out
